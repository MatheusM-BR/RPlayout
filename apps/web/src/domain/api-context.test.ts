import {afterEach,describe,expect,it,vi} from 'vitest'
import {api} from '../api.js'
import {clientContext,SupersededContextError} from './client-context.js'
import {commitSnapshot} from './snapshot-commit.js'
import type {Snapshot} from '../types.js'

afterEach(()=>{vi.restoreAllMocks();clientContext.nextSession()})
const snapshot=(channelId:string)=>({view:{channel:{id:channelId}},live:{transport:{channelId}},monitors:{},history:{}} as unknown as Snapshot)
const reply=(body:unknown)=>new Response(JSON.stringify(body),{status:200})
describe('API usada pela tela e commit de operação',()=>{
  it('zonas, grafismos e eventos enviam somente a revisão capturada, e a abertura pode conferir essa mesma revisão',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(async()=>reply(snapshot('a')))
    await api.saveProtectedZones('rd',[],[],43)
    await api.itemGraphics('item',43)
    await api.addItemGraphic('item','template',{title:'Draft'},5,43)
    await api.removeItemGraphic('cue',43)
    await api.addSecondaryEvent('item',{name:'Draft',targetLayer:'LOWER_THIRD',triggerMode:'MANUAL',offsetFrames:0,templateId:'',payload:{},enabled:true,type:'GRAPHICS_OVERLAY'},43)
    await api.removeSecondaryEvent('item','event',43)
    expect(fetcher).toHaveBeenCalledTimes(6)
    for(const [,request] of fetcher.mock.calls)expect(new Headers(request?.headers).get('If-Match')).toBe('w/"43"')
    expect(fetcher.mock.calls.map(([,request])=>request?.method??'GET')).toEqual(['PUT','GET','POST','DELETE','POST','DELETE'])
  })
  it('publicação e rollback conservam a versão e a conferência explícitas, sem buscar outro plano na confirmação',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(async()=>reply(snapshot('a'))),token='A'.repeat(43)
    await api.publishOperationalPlaylist('rd',37,token)
    await api.reviewOperationalRollback('rd','revision 1',37)
    await api.rollbackOperationalPlaylist('rd','revision 1',37,token)
    expect(fetcher).toHaveBeenCalledTimes(3)
    for(const [,request] of fetcher.mock.calls)expect(new Headers(request?.headers).get('If-Match')).toBe('w/"37"')
    expect(fetcher.mock.calls[1]?.[0]).toBe('/api/rundowns/rd/operational-rollback-review?revisionId=revision%201')
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual({reviewToken:token})
    expect(JSON.parse(String(fetcher.mock.calls[2]?.[1]?.body))).toEqual({revisionId:'revision 1',reviewToken:token})
  })
  it('resposta de transporte real da API tem proveniência; canal atual não muda geração',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockResolvedValue(reply(snapshot('a'))),apply=vi.fn(),ticket=clientContext.capture()
    const result=await api.transport('a','cue',{itemId:'vt'})
    expect(commitSnapshot(clientContext,result,'a',apply)).toBe(true)
    expect(clientContext.current(ticket)).toBe(true);expect(apply).toHaveBeenCalledOnce();expect(fetcher).toHaveBeenCalledOnce()
    expect(JSON.parse(String(fetcher.mock.calls[0]?.[1]?.body))).toEqual({action:'cue',itemId:'vt'})
  })
  it('carregar canal novo invalida respostas/fila do foco anterior antes de aplicar',async()=>{
    vi.spyOn(globalThis,'fetch').mockResolvedValue(reply(snapshot('b')))
    const ticket=clientContext.capture(),result=await api.rundown('rd-b'),apply=vi.fn()
    expect(commitSnapshot(clientContext,result,'a',apply)).toBe(true)
    expect(clientContext.current(ticket)).toBe(false);expect(apply).toHaveBeenCalledOnce()
    expect(commitSnapshot(clientContext,result,'b',apply)).toBe(false)
  })
  it('objeto clonado/local não pode reinstalar operação; envelope aninhado da API pode',async()=>{
    vi.spyOn(globalThis,'fetch').mockResolvedValue(reply({nested:snapshot('a')}))
    const result=await api.audit(),apply=vi.fn(),nested=(result as unknown as {nested:Snapshot}).nested
    expect(commitSnapshot(clientContext,{...nested},'a',apply)).toBe(false)
    expect(commitSnapshot(clientContext,nested,'a',apply)).toBe(true)
    expect(apply).toHaveBeenCalledOnce()
  })
  it('TAKE já enviado, resposta tardia e sessão nova não criam sucesso nem retry',async()=>{
    let release!:(value:Response)=>void
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(()=>new Promise(resolve=>{release=resolve}))
    const pending=api.transport('a','take');clientContext.nextSession();release(reply(snapshot('a')))
    await expect(pending).rejects.toBeInstanceOf(SupersededContextError)
    expect(fetcher).toHaveBeenCalledOnce()
  })
  it('edições estruturais enviam a revisão exibida, sem buscar uma nova revisão para forçar a gravação',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(async()=>reply(snapshot('a')))
    await api.patchItem('item',{title:'A'},22)
    await api.moveItem('item',2,22)
    await api.addItem('rd',{type:'LIVE',sourceRef:'ndi:Estúdio'},22)
    await api.removeItem('item',22)
    await api.bulkDeleteItems('rd',['item'],22)
    await api.group('rd',['one','two'],22)
    await api.ungroup('block',22)
    expect(fetcher).toHaveBeenCalledTimes(7)
    for(const [,request] of fetcher.mock.calls)expect(new Headers(request?.headers).get('If-Match')).toBe('w/"22"')
    expect(fetcher.mock.calls.map(([,request])=>request?.method)).toEqual(['PATCH','POST','POST','DELETE','POST','POST','POST'])
  })
  it('edição sem revisão não envia nada ao servidor',()=>{
    const fetcher=vi.spyOn(globalThis,'fetch')
    expect(()=>api.addItem('rd',{type:'LIVE'},undefined)).toThrow('Atualize a grade')
    expect(()=>api.removeItem('item',undefined)).toThrow('Atualize a grade')
    expect(()=>api.group('rd',['one','two'],undefined)).toThrow('Atualize a grade')
    expect(()=>api.setTrim('item',{in:0,out:100},'ITEM',undefined)).toThrow('Atualize a grade')
    expect(()=>api.setAudio('item',{mode:'MANUAL',gainDb:-3,measured:null},'ITEM',undefined)).toThrow('Atualize a grade')
    expect(fetcher).not.toHaveBeenCalled()
  })
  it('desfazer, importação e montagem enviam a revisão de abertura; proposta não muda a grade',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(async()=>reply(snapshot('a')))
    await api.undo('rd',27);await api.redo('rd',27)
    await api.loadPlaylist('rd','C:/list.m3u',false,undefined,27)
    await api.loadPlaylistText('rd','C:/vt.mp4',true,undefined,27)
    await api.autoFill('rd',{proposalId:'review-window'},27);await api.autoFillDay('rd',27,{proposalId:'review-day'})
    expect(fetcher).toHaveBeenCalledTimes(6)
    for(const [,request] of fetcher.mock.calls)expect(new Headers(request?.headers).get('If-Match')).toBe('w/"27"')
    await api.autoFill('rd',{minutes:5,preview:true},undefined)
    expect(new Headers(fetcher.mock.calls[6]?.[1]?.headers).has('If-Match')).toBe(false)
    expect(JSON.parse(String(fetcher.mock.calls[4]?.[1]?.body))).toEqual({proposalId:'review-window'})
    expect(JSON.parse(String(fetcher.mock.calls[5]?.[1]?.body))).toEqual({proposalId:'review-day'})
    await api.autoFillDay('rd',27,{preview:true})
    expect(new Headers(fetcher.mock.calls[7]?.[1]?.headers).get('If-Match')).toBe('w/"27"')
  })
  it('corte e nível usam a revisão de abertura; trilha vai na mesma confirmação do áudio',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(async()=>reply(snapshot('a')))
    await api.setTrim('item',{in:25,out:250},'ITEM',29)
    await api.setAudio('item',{mode:'MANUAL',gainDb:-3,measured:null},'ITEM',29,1)
    expect(fetcher).toHaveBeenCalledTimes(2)
    for(const [,request] of fetcher.mock.calls)expect(new Headers(request?.headers).get('If-Match')).toBe('w/"29"')
    expect(JSON.parse(String(fetcher.mock.calls[1]?.[1]?.body))).toMatchObject({scope:'ITEM',audioTrack:1,audio:{gainDb:-3}})
  })
  it('revisão dos alvos e confirmação ampla conservam a revisão de abertura',async()=>{
    const fetcher=vi.spyOn(globalThis,'fetch').mockImplementation(async()=>reply(snapshot('a'))),token='A'.repeat(43)
    await api.editScope('item','ALL_RUNDOWNS',31)
    await api.setTrim('item',{in:25,out:250},'ALL_RUNDOWNS',31,token)
    await api.setAudio('item',{mode:'MANUAL',gainDb:-3,measured:null},'ASSET_DEFAULT',31,1,token)
    expect(fetcher).toHaveBeenCalledTimes(3)
    expect(fetcher.mock.calls[0]?.[1]?.method??'GET').toBe('GET')
    for(const [,request] of fetcher.mock.calls)expect(new Headers(request?.headers).get('If-Match')).toBe('w/"31"')
    for(const [,request] of fetcher.mock.calls.slice(1))expect(JSON.parse(String(request?.body)).scopeReviewToken).toBe(token)
  })
})
